#!/usr/bin/env bash
# Builds the patched UxPlay engine for Linux into
# apps/desktop/src-tauri/resources/engine. Unlike on Windows, GStreamer is not
# bundled: the .deb depends on the system's (see tauri.linux.conf.json).
#
# Needs: build-essential cmake ninja-build pkg-config libssl-dev libplist-dev
#        libgstreamer1.0-dev libgstreamer-plugins-base1.0-dev
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC="$REPO/engine/uxplay"
PATCHES="$REPO/engine/patches"
OUT="$REPO/apps/desktop/src-tauri/resources/engine"
WORK="${MIRLOW_BUILD_DIR:-$HOME/.cache/mirlow-build}/engine"

[ -f "$SRC/CMakeLists.txt" ] || { echo "engine/uxplay is empty: run 'git submodule update --init'"; exit 1; }

rm -rf "$WORK"
mkdir -p "$WORK/src"
(cd "$SRC" && tar --exclude=.git -cf - .) | tar -xf - -C "$WORK/src"
# A Windows checkout has CRLF line endings, which the patches do not.
find "$WORK/src" -type f \( -name '*.c' -o -name '*.h' -o -name '*.cpp' -o -name '*.txt' -o -name '*.cmake' \) \
  -exec sed -i 's/\r$//' {} +
for p in "$PATCHES"/*.patch; do
  echo "applying $(basename "$p")"
  sed 's/\r$//' "$p" | patch -d "$WORK/src" -p1 --forward --no-backup-if-mismatch
done

cmake -S "$WORK/src" -B "$WORK/build" -G Ninja -DCMAKE_BUILD_TYPE=Release
cmake --build "$WORK/build"

rm -rf "$OUT"
mkdir -p "$OUT/bin" "$OUT/licenses/uxplay"
install -m 755 -s "$WORK/build/uxplay" "$OUT/bin/mirlow-engine"
cp "$SRC/LICENSE" "$OUT/licenses/uxplay/LICENSE"
cp "$SRC/lib/llhttp/LICENSE-MIT" "$OUT/licenses/uxplay/llhttp-LICENSE-MIT"
cp "$PATCHES"/*.patch "$OUT/licenses/uxplay/"
{
  echo "# Mirlow engine runtime (Linux)"
  echo
  echo "Generated by \`scripts/linux/build-engine.sh\`. Do not edit by hand."
  echo
  echo "## UxPlay (GPL-3.0-or-later)"
  echo
  echo "- Upstream: https://github.com/FDH2/UxPlay"
  echo "- Commit: \`$(cat "$REPO/engine/UXPLAY_COMMIT" | tr -d '\r')\`"
  echo "- Modifications: the patches in \`engine/patches/\` of the Mirlow repository"
  echo
  echo "GStreamer, OpenSSL and libplist are the system's own, installed as dependencies of the package."
} > "$OUT/THIRD-PARTY-RUNTIME.md"
echo "engine: $OUT/bin/mirlow-engine"
